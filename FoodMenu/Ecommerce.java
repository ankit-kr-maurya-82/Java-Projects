class Ecommerce {

    public static void line(int l){
        for(int i=0;i<l;i++){
            System.out.print("-");
        }
    }

    public static void linebreak(){
        System.out.println();
    }
    public static void main(String[] args){
        line(30);
        linebreak();
        System.out.println("Ecommerce Platform");
        line(30);
        linebreak();
        
    }
}